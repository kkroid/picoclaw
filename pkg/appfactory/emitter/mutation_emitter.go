// renderInventoryFormController 生成 inventory profile 的 record_form_controller.dart。
func renderInventoryFormController() string {
	return strings.Join([]string{
		"import 'package:flutter/material.dart';",
		"",
		"import '../models/inventory_sheet.dart';",
		"import '../models/line_item.dart';",
		"import '../models/sku.dart';",
		"import '../models/warehouse.dart';",
		"import '../repositories/record_repository.dart';",
		"",
		"class RecordFormController extends ChangeNotifier {",
		"  RecordFormController({",
		"    required this.repository,",
		"    List<Warehouse> warehouses = const [],",
		"    List<Sku> skus = const [],",
		"    InventorySheet? initialSheet,",
		"    List<LineItem>? initialItems,",
		"  })  : _warehouses = List<Warehouse>.of(warehouses),",
		"        _skus = List<Sku>.of(skus),",
		"        warehouseController = TextEditingController(",
		"          text: initialSheet?.warehouseId ?? (warehouses.isNotEmpty ? warehouses.first.warehouseId : ''),",
		"        ),",
		"        countedOnController = TextEditingController(",
		"          text: _formatInventoryDate(initialSheet?.countedOn ?? DateTime.now()),",
		"        ),",
		"        noteController = TextEditingController(text: initialSheet?.note ?? ''),",
		"        _initialSheet = initialSheet,",
		"        _lineItems = List<LineItem>.of(initialItems ?? const <LineItem>[]),",
		"        _selectedStatus = initialSheet?.status ?? InventorySheetStatus.draft;",
		"",
		"  final RecordRepository repository;",
		"  final List<Warehouse> _warehouses;",
		"  final List<Sku> _skus;",
		"  final TextEditingController warehouseController;",
		"  final TextEditingController countedOnController;",
		"  final TextEditingController noteController;",
		"  final InventorySheet? _initialSheet;",
		"  final List<LineItem> _lineItems;",
		"",
		"  InventorySheetStatus _selectedStatus;",
		"  int _nextDraftSeed = 0;",
		"",
		"  bool get isEditing => _initialSheet != null;",
		"  List<Warehouse> get warehouses => List.unmodifiable(_warehouses);",
		"  List<Sku> get skus => List.unmodifiable(_skus);",
		"  InventorySheetStatus get selectedStatus => _selectedStatus;",
		"  DateTime get selectedCountedOn => DateTime.tryParse(countedOnController.text.trim()) ?? DateTime.now();",
		"  List<LineItem> get lineItems => List.unmodifiable(_lineItems);",
		"",
		"  void setStatus(InventorySheetStatus status) {",
		"    if (_selectedStatus == status) {",
		"      return;",
		"    }",
		"    _selectedStatus = status;",
		"    notifyListeners();",
		"  }",
		"",
		"  void setWarehouse(String warehouseId) {",
		"    if (warehouseController.text == warehouseId) {",
		"      return;",
		"    }",
		"    warehouseController.text = warehouseId;",
		"    notifyListeners();",
		"  }",
		"",
		"  void setCountedOn(DateTime value) {",
		"    countedOnController.text = _formatInventoryDate(value);",
		"    notifyListeners();",
		"  }",
		"",
		"  void addLineItem({String? skuId, int expectedQty = 0, int countedQty = 0}) {",
		"    final resolvedSkuId = skuId ?? (_skus.isNotEmpty ? _skus.first.skuId : '');",
		"    _lineItems.add(",
		"      LineItem(",
		"        lineItemId: _nextGeneratedId('line'),",
		"        sheetId: _initialSheet?.sheetId ?? '',",
		"        skuId: resolvedSkuId,",
		"        expectedQty: expectedQty,",
		"        countedQty: countedQty,",
		"        varianceQty: countedQty - expectedQty,",
		"      ),",
		"    );",
		"    notifyListeners();",
		"  }",
		"",
		"  void updateLineItem(String lineItemId, {String? skuId, int? expectedQty, int? countedQty}) {",
		"    final index = _lineItems.indexWhere((item) => item.lineItemId == lineItemId);",
		"    if (index < 0) {",
		"      return;",
		"    }",
		"    final current = _lineItems[index];",
		"    final nextExpectedQty = expectedQty ?? current.expectedQty;",
		"    final nextCountedQty = countedQty ?? current.countedQty;",
		"    _lineItems[index] = LineItem(",
		"      lineItemId: current.lineItemId,",
		"      sheetId: current.sheetId,",
		"      skuId: skuId ?? current.skuId,",
		"      expectedQty: nextExpectedQty,",
		"      countedQty: nextCountedQty,",
		"      varianceQty: nextCountedQty - nextExpectedQty,",
		"    );",
		"    notifyListeners();",
		"  }",
		"",
		"  void removeLineItem(String lineItemId) {",
		"    _lineItems.removeWhere((item) => item.lineItemId == lineItemId);",
		"    notifyListeners();",
		"  }",
		"",
		"  Future<InventorySheet> submit() async {",
		"    final warehouseId = warehouseController.text.trim();",
		"    if (warehouseId.isEmpty) {",
		"      throw const FormatException('请选择所属仓库');",
		"    }",
		"    if (_lineItems.isEmpty) {",
		"      throw const FormatException('请至少添加一个明细项');",
		"    }",
		"",
		"    final sheetId = _initialSheet?.sheetId ?? _nextGeneratedId('sheet');",
		"    final note = noteController.text.trim();",
		"    final sheet = InventorySheet(",
		"      sheetId: sheetId,",
		"      warehouseId: warehouseId,",
		"      status: _selectedStatus,",
		"      countedOn: selectedCountedOn,",
		"      note: note.isEmpty ? null : note,",
		"    );",
		"",
		"    if (isEditing) {",
		"      await repository.updateInventorySheet(sheet);",
		"    } else {",
		"      await repository.addInventorySheet(sheet);",
		"    }",
		"",
		"    final nextItems = (await repository.loadLineItems())",
		"        .where((item) => item.sheetId != sheetId)",
		"        .toList(growable: true)",
		"      ..addAll(",
		"        _lineItems.map((item) {",
		"          final resolvedLineItemId = item.lineItemId.trim().isEmpty ? _nextGeneratedId('line') : item.lineItemId;",
		"          final expectedQty = item.expectedQty;",
		"          final countedQty = item.countedQty;",
		"          return LineItem(",
		"            lineItemId: resolvedLineItemId,",
		"            sheetId: sheetId,",
		"            skuId: item.skuId,",
		"            expectedQty: expectedQty,",
		"            countedQty: countedQty,",
		"            varianceQty: countedQty - expectedQty,",
		"          );",
		"        }),",
		"      );",
		"    await repository.saveLineItems(nextItems);",
		"    return sheet;",
		"  }",
		"",
		"  String _nextGeneratedId(String prefix) {",
		"    final seed = DateTime.now().microsecondsSinceEpoch + _nextDraftSeed;",
		"    _nextDraftSeed += 1;",
		"    return '$prefix-$seed';",
		"  }",
		"",
		"  @override",
		"  void dispose() {",
		"    warehouseController.dispose();",
		"    countedOnController.dispose();",
		"    noteController.dispose();",
		"    super.dispose();",
		"  }",
		"}",
		"",
		"String _formatInventoryDate(DateTime value) {",
		"  final month = value.month.toString().padLeft(2, '0');",
		"  final day = value.day.toString().padLeft(2, '0');",
		"  return '${value.year}-$month-$day';",
		"}",
	}, "\n") + "\n"
}

