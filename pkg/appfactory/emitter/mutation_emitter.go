// MutationEmitResult 表示 MutationEmitter 的输出。
type MutationEmitResult struct {
	FormPageContent       string
	FormPagePath          string
	FormControllerContent string
	FormControllerPath    string
}

// EmitMutation 从 DomainModel 确定性生成 record_form_page.dart 和 record_form_controller.dart。
// 返回 (result, true) 表示成功；(zero, false) 表示当前 DomainModel 不在可 emit 范围内。
// 仅支持 relation-rich profile（project-task-tag、inventory-sheet-line-item），
// generic profile 的 Repository-driven 函数依赖 workspace 文件系统推断类型，不属于纯 DomainModel 输入，返回 false。
func EmitMutation(dm appprepare.DomainModel) (MutationEmitResult, bool) {
	profile := identifyCopyProfile(dm)
	switch profile {
	case copyProfileProjectTaskTag:
		return MutationEmitResult{
			FormPageContent:       renderProjectTaskTagFormPage(),
			FormPagePath:          "lib/views/record_form_page.dart",
			FormControllerContent: renderProjectTaskTagFormController(),
			FormControllerPath:    "lib/controllers/record_form_controller.dart",
		}, true
	case copyProfileInventorySheetLineItem:
		return MutationEmitResult{
			FormPageContent:       renderInventoryFormPage(),
			FormPagePath:          "lib/views/record_form_page.dart",
			FormControllerContent: renderInventoryFormController(),
			FormControllerPath:    "lib/controllers/record_form_controller.dart",
		}, true
	default:
		return MutationEmitResult{}, false
	}
}

